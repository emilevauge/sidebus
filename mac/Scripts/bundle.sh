#!/bin/bash
#
# Construit mac/build/Sidebus.app et le signe en ad hoc.
#
# Signing: a local codesigning identity when the keychain holds one, ad hoc otherwise. The
# difference matters to TCC, which remembers permissions (Screen Recording, Accessibility,
# Local Network) by signing rule:
#
#   ad hoc   -> "identifier app.sidebus and cdhash H<...>"   changes on every build, so
#               the permission is lost on every rebuild
#   identity -> "identifier app.sidebus and certificate leaf = H<...>"   stable
#
# Force a choice with SIDEBUS_CODESIGN_IDENTITY (the identity name, or "-" for ad hoc).
# La signature Developer ID et la notarisation arrivent en phase 9.
#
# Usage: Scripts/bundle.sh [release|debug]   (default: release)

set -euo pipefail

CONFIG="${1:-release}"
MAC_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
APP="$MAC_DIR/build/Sidebus.app"

cd "$MAC_DIR"

# The phone half of calls, carried as a resource and pushed to the phone over adb.
echo "==> android/callbridge"
"$MAC_DIR/../android/callbridge/build.sh" "$MAC_DIR/Sources/SidebusApp/Resources/callbridge.dex"

echo "==> swift build -c $CONFIG"
swift build -c "$CONFIG"

BIN="$(swift build -c "$CONFIG" --show-bin-path)/SidebusApp"
if [[ ! -x "$BIN" ]]; then
	echo "binary not found: $BIN" >&2
	exit 1
fi

echo "==> assembling $APP"
rm -rf "$APP"
mkdir -p "$APP/Contents/MacOS" "$APP/Contents/Resources"
cp "$BIN" "$APP/Contents/MacOS/SidebusApp"
cp "$MAC_DIR/Resources/Info.plist" "$APP/Contents/Info.plist"
printf 'APPL????' > "$APP/Contents/PkgInfo"

# Version stamped from the VERSION file at the repository root, the single source of truth
# shared with the Android app. The update checker compares the running bundle's
# CFBundleShortVersionString with the latest GitHub release tag, so a bundle built with a
# stale version would offer an update to itself.
VERSION="$(cat "$MAC_DIR/../VERSION")"
/usr/libexec/PlistBuddy -c "Set :CFBundleShortVersionString $VERSION" "$APP/Contents/Info.plist"
/usr/libexec/PlistBuddy -c "Set :CFBundleVersion $VERSION" "$APP/Contents/Info.plist"

# Application icon, declared by CFBundleIconFile. Regenerated by art/build.sh.
cp "$MAC_DIR/Resources/Sidebus.icns" "$APP/Contents/Resources/Sidebus.icns"

# SwiftPM resource bundle: it carries the menu bar templates, which Bundle.module looks
# for in Contents/Resources.
RESOURCES="$(swift build -c "$CONFIG" --show-bin-path)/Sidebus_SidebusApp.bundle"
if [[ -d "$RESOURCES" ]]; then
	cp -R "$RESOURCES" "$APP/Contents/Resources/"
else
	echo "resource bundle not found: $RESOURCES" >&2
	exit 1
fi

IDENTITY="${SIDEBUS_CODESIGN_IDENTITY:-}"
if [[ -z "$IDENTITY" ]]; then
	IDENTITY="$(security find-identity -v -p codesigning | awk -F'"' 'NR==1 && NF>1 {print $2}')"
	IDENTITY="${IDENTITY:--}"
fi

if [[ "$IDENTITY" == "-" ]]; then
	echo "==> ad hoc signing (TCC permissions lost on every build)"
else
	echo "==> signing with identity \"$IDENTITY\""
fi
codesign --force --sign "$IDENTITY" --identifier app.sidebus --timestamp=none "$APP"
codesign --verify --verbose=2 "$APP"

echo
echo "ready: $APP"
echo "run: open $APP"
